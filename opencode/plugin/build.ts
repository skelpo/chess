/**
 * Compiles the board's TSX for the npm package. opencode compiles a plugin's TSX itself (Solid for
 * opentui) only outside node_modules, so a package installed with `opencode plugin add` must ship
 * JavaScript. Same transform as opencode: babel-preset-solid (universal, @opentui/solid) + TypeScript.
 *
 * Usage (from opencode/plugin, after `npm install`): node build.ts   (`npm pack` / `npm publish` run it)
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const here = fileURLToPath(new URL(".", import.meta.url));
const require = createRequire(import.meta.url);
type Babel = { transformAsync(code: string, options: Record<string, unknown>): Promise<{ code?: string | null } | null> };
const babel = require("@babel/core") as Babel;
const solid = require.resolve("babel-preset-solid");
const typescript = require.resolve("@babel/preset-typescript");

// dist/ sits one level down: point plain-TS imports back up, and compiled siblings at their .js files.
const rewrite = (code: string) =>
  code
    .replaceAll(/from "\.\/(board|tui)\.tsx"/g, 'from "./$1.js"')
    .replaceAll(/from "\.\/((?:lib\/)?[\w-]+\.ts)"/g, 'from "../$1"');

mkdirSync(here + "dist", { recursive: true });
for (const name of ["tui", "board"]) {
  const filename = here + name + ".tsx";
  const result = await babel.transformAsync(readFileSync(filename, "utf8"), {
    filename,
    configFile: false,
    babelrc: false,
    presets: [[solid, { moduleName: "@opentui/solid", generate: "universal" }], [typescript, {}]],
  });
  if (typeof result?.code !== "string") throw new Error("Could not compile " + filename);
  writeFileSync(here + "dist/" + name + ".js", "// Generated by build.ts from " + name + ".tsx. Do not edit.\n" + rewrite(result.code) + "\n");
}
console.log("opencode/plugin/dist built");
